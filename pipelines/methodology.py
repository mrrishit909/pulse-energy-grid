"""Render docs/METHODOLOGY.md from the published artifacts so every number in it is the number in the artifact."""
from __future__ import annotations

import json

from pipelines.common import PUBLIC, ROOT


def L(name):
    return json.loads((PUBLIC / f"{name}.json").read_text())


def write() -> None:
    meta, facts, fe, rec, qual, wr, mix = L("meta"), L("facts"), L("forecast_eval"), L("reconciliation"), L("quality"), L("weather_relation"), L("fuel_mix")
    dm, dr = L("dispatch_model"), L("dispatch_results")
    o = []
    w = o.append
    w("# Methodology\n\nGenerated by `pipelines/methodology.py` from the published artifacts (do not edit by hand). Every number below is the number in `site/public/data/`.\n")
    w(f"## Window and split\nUTC hours {meta['window_utc'][0]} to {meta['window_utc'][1]} ({meta['hours_in_window']:,} hourly slots per balancing authority). Train {meta['split']['train'][0]} to {meta['split']['train'][1]}; "
      f"validation to {meta['split']['val'][1]}; test after that. Split is by the UTC time of the forecast target hour. Hyper-parameters are chosen on validation (train-only fit); the deployed models are refit on train plus validation; the test period is never used for any choice.\n")
    w("## Ingestion and cleaning\nEBA.zip is streamed once (`pipelines/ingestion/eia.py`); NOAA ISD station files are reduced to one observation per station-hour (`pipelines/ingestion/noaa.py`). `pipelines/cleaning/clean.py` builds the full UTC grid, flags null / range / spike values, "
      "linearly fills runs of at most 3 hours (flagged `imputed`, never used as targets) and builds the population-weighted BA temperature. Local time uses IANA zones, so DST days have 23 or 25 hours (see `quality.json`).\n")
    w("| BA | series | raw rows | kept | missing slots | null | flagged | imputed |\n|---|---|---|---|---|---|---|---|")
    for r in rec["ledger"]:
        if r["kind"] in ("D", "DF", "NG", "TI"):
            w(f"| {r['ba']} | {r['kind']} | {r['raw_rows']:,} | {r['kept']:,} | {r['missing_slots']:,} | {r['null_value']:,} | {r['flagged_outlier']:,} | {r['imputed_short_gap']:,} |")
    w("\nFuel series are in `reconciliation.json` (all 15 reconcile exactly: grid slots = raw rows + missing; raw rows = kept + null + flagged).\n")
    for ba in meta["bas"]:
        g, b = rec["generation_vs_total"][ba], rec["balance"][ba]
        w(f"- **{ba}** sum of fuels vs total net generation: mean signed {g['mean_signed_resid_pct']:.3f}%, mean absolute {g['mean_abs_resid_pct']:.3f}%, P99 absolute {g['p99_abs_resid_pct']:.2f}%, {g['hours_gt_2pct']:,} hours beyond 2%. "
          f"Net generation - demand - interchange: mean {b['mean_resid_mw']:.1f} MW, mean absolute {b['mean_abs_resid_mw']:.1f} MW (EIA identity).")
    w("\n## Forecasting\nForecast origin is local midnight starting the target day. Models: seasonal naive (same hour last week), the EIA day-ahead forecast, EIA debiased with the trailing 28-day actual/forecast ratio, and quantile gradient boosting "
      "(scikit-learn `HistGradientBoostingRegressor`, LightGBM unavailable on this machine; see DATA_SOURCES.md) in three variants. Target is demand divided by a level (trailing 7-day mean, or the EIA forecast for the stacked variant). P10/P50/P90 are separate quantile fits; "
      "an 80% interval is conformalised with the CQR offset computed on validation.\n")
    for ba, e in fe["bas"].items():
        w(f"### {ba} test period ({e['common_test_hours']:,} common hours)\n\n| model | MAPE % | MAE MW | RMSE MW | bias MW | peak-5% MAPE % | deployable |\n|---|---|---|---|---|---|---|")
        for k, m in e["models"].items():
            w(f"| {k} | {m['mape_pct']:.2f} | {m['mae_mw']:,.0f} | {m['rmse_mw']:,.0f} | {m['bias_mw']:,.0f} | {m['mape_peak5_pct']:.2f} | {'yes' if m['available_at_forecast_time'] else 'no (upper bound)'} |")
        w("")
        for c in e["comparisons"]:
            w(f"- {c['statement']}")
        iv = e["intervals"]["gbm"]
        w(f"- 80% interval (gbm): raw coverage {iv['raw_coverage_pct']:.1f}%, conformal coverage {iv['cqr_coverage_pct']:.1f}%, mean width {iv['cqr_mean_width_mw']:,.0f} MW.\n")
    w("### Drift of the EIA day-ahead forecast\n")
    w("Bias = 100 x mean(EIA-930 day-ahead demand forecast - demand) / mean(demand) per local calendar year, over hours where both are clean "
      "(years with at least 1000 such hours; negative = the BA's own forecast ran low). It is `facts.bas[ba].eia_dayahead_bias_pct_by_year`; "
      f"`facts.eia_ciso_dayahead_bias_pct` = {facts['eia_ciso_dayahead_bias_pct']:+.2f}% is the CISO value in {facts['eia_ciso_dayahead_bias_year']} (partial year). "
      "Part of the GBM's margin over the EIA forecast in CISO is this drift in the published series, which is why `eia_debiased` is reported beside it.\n")
    w("| BA | " + " | ".join(facts["bas"]["CISO"]["eia_dayahead_bias_pct_by_year"]) + " |\n|---|" + "---|" * len(facts["bas"]["CISO"]["eia_dayahead_bias_pct_by_year"]))
    for ba in ("CISO", "ERCO"):
        w(f"| {ba} | " + " | ".join(f"{v:+.2f}%" for v in facts["bas"][ba]["eia_dayahead_bias_pct_by_year"].values()) + " |")
    w("")
    w("## Demand and weather\n")
    for ba, x in wr["bas"].items():
        w(f"- **{ba}**: cooling base {x['cool_base_c']:.0f} C, heating base {x['heat_base_c']:.0f} C, +{x['pct_demand_per_c_above_base']:.2f}% demand per degC above the cooling base in the afternoon hours (day-bootstrap CI {x['pct_ci'][0]:.2f} to {x['pct_ci'][1]:.2f}; association only).")
    w("\n## Dispatch LP\n" + dm["formulation"]["summary"] + "\n")
    for k in ("variables", "constraints"):
        for s in dm["formulation"][k]:
            w(f"- {s}")
    w("\nAll cost, ramp, battery and fuel-price parameters are assumptions (SIMULATED) listed in `dispatch_model.json`; capacities are the maximum observed hourly generation of each fuel. Reported cost = HiGHS objective; the per-class breakdown sums to it (tested).\n")
    w("| BA | day | scenario | objective (USD) | unserved MWh | max price USD/MWh |\n|---|---|---|---|---|---|")
    for ba in dr["bas"]:
        for day, sc in dr["bas"][ba]["days"].items():
            for s, r in sc.items():
                w(f"| {ba} | {day} | {s} | {r['objective_usd']:,.0f} | {r['unserved_mwh']:,.0f} | {max(r['price_usd_mwh']):,.1f} |")
    (ROOT / "docs" / "METHODOLOGY.md").write_text("\n".join(o) + "\n")
